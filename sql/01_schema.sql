CREATE TABLE ptd_team_members (
  member_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name  VARCHAR2(100) NOT NULL,
  email      VARCHAR2(150) NOT NULL,
  role       VARCHAR2(60),
  CONSTRAINT ptd_team_members_email_uk UNIQUE (email)
);

CREATE TABLE ptd_projects (
  project_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_name VARCHAR2(150) NOT NULL,
  description  VARCHAR2(4000),
  owner_id     NUMBER        NOT NULL REFERENCES ptd_team_members (member_id),
  priority     VARCHAR2(10)  DEFAULT 'Medium' NOT NULL,
  status       VARCHAR2(20)  DEFAULT 'Planning' NOT NULL,
  start_date   DATE          NOT NULL,
  due_date     DATE          NOT NULL,
  completed_on DATE,
  CONSTRAINT ptd_projects_priority_ck CHECK (priority IN ('High', 'Medium', 'Low')),
  CONSTRAINT ptd_projects_status_ck   CHECK (status IN ('Planning', 'In progress', 'On hold', 'Completed')),
  CONSTRAINT ptd_projects_dates_ck    CHECK (due_date >= start_date)
);

CREATE TABLE ptd_tasks (
  task_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  NUMBER        NOT NULL REFERENCES ptd_projects (project_id) ON DELETE CASCADE,
  task_title  VARCHAR2(200) NOT NULL,
  assignee_id NUMBER        REFERENCES ptd_team_members (member_id),
  is_done     VARCHAR2(1)   DEFAULT 'N' NOT NULL,
  done_on     DATE,
  CONSTRAINT ptd_tasks_done_ck CHECK (is_done IN ('Y', 'N'))
);

CREATE INDEX ptd_tasks_project_ix ON ptd_tasks (project_id);
CREATE INDEX ptd_projects_owner_ix ON ptd_projects (owner_id);

-- Dashboard view: one row per project with progress and schedule flags
CREATE OR REPLACE VIEW ptd_project_status_v AS
SELECT p.project_id,
       p.project_name,
       m.full_name AS owner_name,
       p.priority,
       p.status,
       p.start_date,
       p.due_date,
       COUNT(t.task_id)                                    AS total_tasks,
       COUNT(CASE WHEN t.is_done = 'Y' THEN 1 END)         AS done_tasks,
       CASE
         WHEN p.status = 'Completed' THEN 100
         WHEN COUNT(t.task_id) = 0 THEN 0
         ELSE ROUND(COUNT(CASE WHEN t.is_done = 'Y' THEN 1 END) / COUNT(t.task_id) * 100)
       END                                                 AS progress_pct,
       CASE WHEN p.status <> 'Completed' AND p.due_date < TRUNC(SYSDATE)
            THEN 'Y' ELSE 'N' END                          AS is_overdue,
       p.due_date - TRUNC(SYSDATE)                         AS days_left
  FROM ptd_projects p
  JOIN ptd_team_members m ON m.member_id = p.owner_id
  LEFT JOIN ptd_tasks t ON t.project_id = p.project_id
 GROUP BY p.project_id, p.project_name, m.full_name, p.priority, p.status, p.start_date, p.due_date;

